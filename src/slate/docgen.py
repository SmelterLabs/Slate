_EVENT_RE = re.compile(r"^[a-z]+(_[a-z]+)*\.[a-z]+(_[a-z]+)*$")
# `noun.verb`-shaped literals that are not event types.
_NOT_EVENTS = {
    "slate.change",
    "slate.flush_checked",  # core._FLUSH_KEY, a session.info key
    "http.request",  # an ASGI message type
    "uvicorn.access",
    "alembic.ini",
    "index.html",
    "build.json",
    "agents.denied",  # agent_rules.KEY, a workspace_settings key
}


def event_types_in_code() -> set[str]:
    """Every `noun.verb` string literal under src/slate that names an event type."""
    found: set[str] = set()
    for path in PKG.rglob("*.py"):
        if path.name == "docgen.py":
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if (
                isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and _EVENT_RE.match(node.value)
                and not node.value.endswith(".id")  # foreign keys: "items.id"
                and node.value not in _NOT_EVENTS
            ):
                found.add(node.value)
    return found


