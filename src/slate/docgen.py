def _sample_params(model: type[BaseModel]) -> BaseModel:
    values: dict[str, Any] = {}
    for name, field in model.model_fields.items():
        if not field.is_required():
            values[name] = field.get_default(call_default_factory=True)
            continue
        ann = str(field.annotation)
        if "int" in ann:
            values[name] = 1
        elif "bool" in ann:
            values[name] = False
        elif "list" in ann:
            values[name] = []
        elif "dict" in ann:
            values[name] = {}
        else:
            values[name] = SAMPLE_ID
    return model.model_construct(**values)


def rest_call(action: Any) -> tuple[str, str] | None:
    """(METHOD, path under /api/v1 as sent) for an MCP action, or None if it cannot say."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # sample params are not real values
            r = action.rest(_sample_params(action.params))
    except Exception:  # noqa: BLE001 - a binding that needs real params; reported as unknown
        return None
    return r.method, API + r.path.split("?")[0]


def mcp_actions() -> list[tuple[str, str, Any]]:
    from slate.mcp_tools import TOOLS

    return [(t, a, act) for t, spec in TOOLS.items() for a, act in spec.actions.items()]


def match_route(method: str, path: str, ops: list[Op] | None = None) -> Op | None:
    for op in ops if ops is not None else rest_ops():
        if op.method == method and _path_regex(op.path).match(path):
            return op
    return None


def mcp_by_route() -> dict[tuple[str, str], list[str]]:
    ops = rest_ops()
    out: dict[tuple[str, str], list[str]] = {}
    for tool, name, action in mcp_actions():
        call = rest_call(action)
        op = match_route(*call, ops) if call else None
        if op is not None:
            out.setdefault((op.method, op.path), []).append(f"{tool} {name}")
    return out


def render_mcp() -> str:
    from slate.mcp_tools import TOOLS

    ops = rest_ops()
    lines = [
        HEADER,
        "# MCP reference\n\n",
        f"{len(TOOLS)} tools at `/mcp` (streamable HTTP, `Authorization: Bearer <token>`) or "
        "over stdio (`slate-mcp` with `SLATE_URL` and `SLATE_TOKEN`). Each tool takes "
        '`{"action": ..., "params": {...}}` (single-action tools take only `params`) and an '
        "optional `session_ref` recorded on every event it writes. Null fields are dropped "
        "from results. Setup: [../mcp.md](../mcp.md).\n\n",
        "`*` marks a required param. **REST** is the call the action makes in stdio mode and "
        "the route that does the same over HTTP.\n\n",
    ]
    for tool, spec in TOOLS.items():
        lines.append(f"## `{tool}`\n\n{spec.about}\n\n")
        lines.append("| Action | Scope | Params | REST | What |\n|---|---|---|---|---|\n")
        for name, action in spec.actions.items():
            fields = action.params.model_fields
            params = ", ".join(
                f"`{k}`" + ("\\*" if f.is_required() else "") for k, f in fields.items()
            )
            call = rest_call(action)
            op = match_route(*call, ops) if call else None
            rest = f"`{op.method} {op.path.removeprefix(API)}`" if op else "—"
            lines.append(
                f"| `{name}` | `{action.scope}` | {params or '—'} | {rest} | {action.doc} |\n"
            )
        lines.append("\n")
    return "".join(lines).rstrip() + "\n"


# --- entry point --------------------------------------------------------------------------


def render_all() -> dict[Path, str]:
    from slate.app import create_app

    app = create_app()
    return {
        OUT / "rest.md": render_rest(app),
        OUT / "mcp.md": render_mcp(),
        OUT / "events.md": render_events(),
    }


def main(check: bool = False) -> int:
    stale = []
    for path, text in render_all().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    rel = [str(p.relative_to(ROOT)) for p in stale]
    if check and stale:
        print("stale, run `uv run slate docs`: " + ", ".join(rel), file=sys.stderr)
        return 1
    print(("wrote " + ", ".join(rel)) if rel else "docs/agents/reference is up to date")
    return 0
