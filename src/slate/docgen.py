@dataclass
class Op:
    method: str
    path: str  # full, e.g. /api/v1/items/{item_id}
    scope: str  # read | write | admin | none | token
    tag: str
    endpoint: Any


def _routers() -> list[Any]:
    """Every router under /api/v1, in mount order (events and recurrences mount separately)."""
    from slate import api
    from slate.api import events, recurrences

    return [m.router for m in api.MODULES] + [events.router, recurrences.router]


def _scope_of(route: Any) -> str:
    for dep in route.dependant.dependencies:
        call = dep.call
        if call.__qualname__ == "require.<locals>.dependency":
            return inspect.getclosurevars(call).nonlocals["scope"]
        if call.__name__ == "stream_auth":
            return "read"
    return "none"


def rest_ops() -> list[Op]:
    """Every documented `/api/v1` route, in router order."""
    ops: list[Op] = []
    for router in _routers():
        for route in router.routes:
            if not getattr(route, "include_in_schema", False) or not hasattr(route, "methods"):
                continue
            path = route.path if route.path.startswith(API) else API + route.path
            for method in sorted(route.methods - {"HEAD"}):
                tag = (route.tags or ["other"])[0]
                ops.append(Op(method, path, _scope_of(route), tag, route.endpoint))
    return ops


def _path_regex(path: str) -> re.Pattern[str]:
    parts = re.split(r"\{[^}]+\}", path)
    return re.compile("^" + "[^/]+".join(map(re.escape, parts)) + "$")


def _cacheable(op: Op) -> bool:
    from slate.fastlane import CACHEABLE

    if op.method != "GET":
        return False
    sample = re.sub(r"\{[^}]+\}", SAMPLE_ID, op.path)
    return bool(CACHEABLE.match(sample))


def _schema_ref(schema: dict[str, Any] | None) -> str | None:
    if not schema:
        return None
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "array" and "$ref" in schema.get("items", {}):
        return "list of " + schema["items"]["$ref"].rsplit("/", 1)[-1]
    return None


def _fields_line(components: dict[str, Any], name: str) -> str:
    schema = components.get(name, {})
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not props:
        return f"`{name}`"
    parts = [f"`{k}`" + ("\\*" if k in required else "") for k in props]
    return f"`{name}`: " + ", ".join(parts)


def _first_paragraph(text: str) -> str:
    para = text.strip().split("\n\n")[0]
    return " ".join(line.strip() for line in para.splitlines())


